function sheet(cells) {
  const s = new E.Sheet({ rows: 40, cols: 12 });
  Object.keys(cells).forEach(a1 => s.setAt(a1, cells[a1]));
  return s;
}
function val(formula, cells) {
  const s = sheet(Object.assign({}, cells || {}, { Z99: '=' + formula.replace(/^=/, '') }));
  return s.get('Z99');
}

