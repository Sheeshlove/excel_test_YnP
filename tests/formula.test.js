let pass = 0, fail = 0;
T.forEach(x => {
  let ok;
  if (typeof x.expected === 'number' && typeof x.actual === 'number') ok = Math.abs(x.actual - x.expected) <= x.tol;
  else ok = x.actual === x.expected;
  if (ok) pass++;
  else { fail++; console.log('  ✗ ' + x.name + '\n      получено: ' + JSON.stringify(x.actual) + '  ожидалось: ' + JSON.stringify(x.expected)); }
});
